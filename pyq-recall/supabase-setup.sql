-- 1. Each person's plan settings
create table if not exists public.pyq_profiles (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  label      text not null default '',
  settings   jsonb not null default '{}'::jsonb,
  is_owner   boolean not null default false,
  updated_at timestamptz not null default now()
);

-- 2. One row per topic a person has started
create table if not exists public.pyq_progress (
  user_id    uuid not null references auth.users(id) on delete cascade,
  topic_id   text not null,
  data       jsonb not null,
  updated_at timestamptz not null default now(),
  primary key (user_id, topic_id)
);

-- 3. Topic list (used by the nightly Claude reminder for titles and pages)
create table if not exists public.pyq_topics (
  id text primary key, title text not null, part int not null,
  vol int not null, page int not null, asked int not null, vol5 jsonb not null default '[]'::jsonb
);

-- 4. Access: only signed-in members of THIS app can read and edit plans (both of you, full access).
alter table public.pyq_profiles enable row level security;
alter table public.pyq_progress enable row level security;
alter table public.pyq_topics   enable row level security;
drop policy if exists "members full access" on public.pyq_profiles;
drop policy if exists "members full access" on public.pyq_progress;
drop policy if exists "members read topics" on public.pyq_topics;
create policy "members full access" on public.pyq_profiles for all to authenticated using (true) with check (true);
create policy "members full access" on public.pyq_progress for all to authenticated using (true) with check (true);
create policy "members read topics" on public.pyq_topics   for select to authenticated using (true);

-- 5. Live sync between devices
do $$ begin
  begin alter publication supabase_realtime add table public.pyq_profiles; exception when others then null; end;
  begin alter publication supabase_realtime add table public.pyq_progress; exception when others then null; end;
end $$;

-- 6. Read-only key for the nightly Claude reminder (cannot change anything)
create table if not exists public.pyq_reminder (token text primary key);
alter table public.pyq_reminder enable row level security;   -- no policies: nobody can read it through the API
insert into public.pyq_reminder (token)
  select md5(random()::text || clock_timestamp()::text) || md5(random()::text)
  where not exists (select 1 from public.pyq_reminder);

create or replace function public.pyq_digest(p_token text)
returns json language sql stable security definer set search_path = public as $$
  select case when exists (select 1 from pyq_reminder where token = p_token) then json_build_object(
    'profiles', (select coalesce(json_agg(json_build_object('user_id', user_id, 'label', label, 'is_owner', is_owner, 'settings', settings)), '[]'::json) from pyq_profiles),
    'progress', (select coalesce(json_agg(json_build_object('user_id', user_id, 'topic_id', topic_id, 'due', data->>'due', 'intro', data->>'intro',
                   'last', data->>'last', 'lastRating', data->>'lastRating', 'lapses', data->'lapses')), '[]'::json) from pyq_progress),
    'topics',   (select json_agg(json_build_object('id', id, 'title', title, 'vol', vol, 'page', page, 'asked', asked)
                   order by asked desc, split_part(id,'.',1)::int, split_part(id,'.',2)::int) from pyq_topics)
  ) else null end
$$;
revoke all on function public.pyq_digest(text) from public;
grant execute on function public.pyq_digest(text) to anon, authenticated;

